#!/bin/bash
# Compiles codec/shaders/bc7_encode.comp to SPIR-V and writes codec/gpu_bc7_spirv.h (checked in, so
# Windows / Mac builds don't need a shader compiler). Needs glslangValidator (glslang-tools) and
# optionally spirv-val (spirv-tools). Run after changing the shader.
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=codec/shaders/bc7_encode.comp
OUT=codec/gpu_bc7_spirv.h
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
glslangValidator -V --target-env vulkan1.0 -o "$TMP/bc7.spv" "$SRC" >/dev/null
if command -v spirv-val >/dev/null; then spirv-val --target-env vulkan1.0 "$TMP/bc7.spv"; fi
python3 - "$TMP/bc7.spv" > "$TMP/h" <<'PY'
import sys, struct
data = open(sys.argv[1], 'rb').read()
words = struct.unpack('<%dI' % (len(data) // 4), data)
print('// Generated by scripts/make-gpu-shaders.sh from shaders/bc7_encode.comp - do not edit.')
print('#pragma once')
print('#include <cstdint>')
print('static const uint32_t kSpvBC7Encode[] = {')
for i in range(0, len(words), 8):
    print('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
print('};')
PY
mv "$TMP/h" "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
